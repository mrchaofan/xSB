/**
 * Seedance (Doubao's video model), as arkcli's asynchronous tasks:
 *
 *   arkcli +gen <prompt> --modality video     -> { task_id }
 *   arkcli gen get <id> --save-to=""          -> { status: { phase } }
 *   arkcli gen get <id> --save-to <dir>       saves the finished video, -> { local_path }
 *   arkcli gen delete <id> --yes              cancels a task that is still queued
 *   arkcli api arkruntime.get_content_generation_task --params '{"id":…}'
 *                                             the task as Ark has it: `seed`, `content.last_frame_url`. `gen get`
 *                                             answers it normalized, and leaves these out (arkcli 1.0.50)
 *
 * A task is `queued`, then `running`, and ends as `succeeded`, `failed`, `cancelled` or `expired` (Ark's video
 * generation API; arkcli reports it as `status.phase`). Deleting a task cancels it only while it is queued: a running
 * one cannot be deleted, and of one that has ended the record is deleted instead.
 *
 * Which Seedance is the user's: the video resource their arkcli profile has
 * (`arkcli profile set-default <id> --modality video`). None is named from here.
 */
import fs from "node:fs";
import path from "node:path";
import { arkcli } from "./arkcli.ts";
import { QUIET, flags, input, saved } from "./ark.ts";
import { arkCost } from "./ark-pricing.ts";
import type { Usage, VideoProvider, VideoRequest, VideoStatus } from "./provider.ts";

/** The task as it is now, with nothing saved. */
const taskOf = (id: string): Promise<any> => arkcli(["gen", "get", id, "--save-to=", "--no-open"]);

export const seedance: VideoProvider = {
  about: `Model: Doubao Seedance (the video model set in the user's arkcli), through arkcli. One clip is one continuous shot. Limits depend on the model version: the 2.0 series makes 4-15 second clips, the 2.5 series 4-30; 480p and 720p everywhere, higher on some. Ratios: 16:9, 9:16, 1:1, 4:3, 3:4, 21:9; with first_frame leave ratio out, the clip takes the image's. reference_images and first_frame cannot be combined. Reference images: at most 9 on the 2.0 series, 30 on the 2.5 series (10 on its flash model). Images travel inside the request: each under 30 MB, 300-6000 pixels a side, width/height between 0.4 and 2.5, and all the images of one call together under about 45 MB, or the request is refused; a JPEG copy of a large PNG is the way to stay under it. An image that shows a real person's face is refused as an input, unless the user has that person's portrait authorised in their Ark account; faces in images generated by Doubao models under the same account are accepted, so pass such an image as the file it was generated to. In the prompt, call the reference images 图片1, 图片2, … in their order and say what to take from each. For changes within one clip, the 2.0 series follows numbered shots in the prompt and ignores timestamps; the 2.5 series follows whole-second timestamps. Spoken lines go in quotation marks. A seed is honoured by some versions only.`,

  async submit(request: VideoRequest): Promise<string> {
    const images = [
      ...(request.firstFrame ? input("first_frame", request.firstFrame) : []),
      ...(request.lastFrame ? input("last_frame", request.lastFrame) : []),
      ...(request.references ?? []).flatMap((image) => input("reference_image", image)),
    ];
    const settings = flags({
      duration: request.duration,
      resolution: request.resolution,
      ratio: request.ratio,
      seed: request.seed,
      "generate-audio": request.audio,
      watermark: false,
      "return-last-frame": request.wantLastFrame || undefined,
    });
    // --save-to="": nothing to save yet; without --wait the task id comes back at once.
    const { task_id } = await arkcli(["+gen", request.prompt, "--modality", "video", ...settings, ...images, "--inline-local", "--save-to=", ...QUIET]);
    if (!task_id) throw new Error("arkcli +gen answered no task id");
    return task_id;
  },

  async poll(id: string): Promise<VideoStatus> {
    const { status, error } = await taskOf(id);
    const phase = status?.phase ?? status;
    if (phase === "queued" || phase === "running") return { status: "pending" };
    if (phase === "succeeded") return { status: "succeeded" };
    // failed, cancelled, expired; and a phase that is none of Ark's is not waited on, as arkcli's own guide has it.
    return { status: "failed", error: status?.message ?? error?.message ?? `the task ended as "${phase}"` };
  },

  async save(id, to) {
    await saved(to.video, (dir) => arkcli(["gen", "get", id, "--save-to", dir, "--no-open"]));
    // The seed and the last frame (a link: it is not among the files arkcli saves) are in the raw task only.
    // The video is saved by now: what cannot be read of them is not there, not a failed generation.
    const raw = await arkcli(["api", "arkruntime.get_content_generation_task", "--params", JSON.stringify({ id })]).catch(() => undefined);
    const link = to.lastFrame && raw?.content?.last_frame_url;
    const frame = link ? await fetch(link).catch(() => undefined) : undefined;
    if (frame?.ok) {
      fs.mkdirSync(path.dirname(path.resolve(to.lastFrame!)), { recursive: true });
      fs.writeFileSync(to.lastFrame!, Buffer.from(await frame.arrayBuffer()));
    }
    const tokens = raw?.usage?.completion_tokens ?? raw?.usage?.total_tokens;
    const usage: Usage | undefined = typeof tokens === "number" ? { unit: "tokens", units: tokens, model: raw?.model, resolution: raw?.resolution } : undefined;
    return { seed: raw?.seed, lastFrame: !!frame?.ok, usage };
  },

  cost: arkCost,

  /**
   * Ark cancels only what has not started: a task that is already running finishes and is billed. Only a queued
   * task is deleted, for deleting one that has ended would remove the record of a video that was paid for.
   */
  async cancel(id: string): Promise<boolean> {
    const queued = await taskOf(id).then((task) => (task.status?.phase ?? task.status) === "queued", () => false);
    return queued && arkcli(["gen", "delete", id, "--yes"]).then(() => true, () => false);
  },
};
