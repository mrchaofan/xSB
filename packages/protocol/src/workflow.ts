export type AssetRef = { name: string; version: string };

/** The last @ separates the version, so a name may contain spaces and @ characters. */
export const formatAssetRef = (ref: AssetRef): string => ref.name + "@" + ref.version;

/** Also accepts the name/version objects stored by earlier Hub and desktop versions. */
export function parseAssetRef(value: unknown): AssetRef | undefined {
  let name: unknown, version: unknown;
  if (typeof value === "string") {
    const at = value.lastIndexOf("@");
    if (at < 1) return;
    name = value.slice(0, at);
    version = value.slice(at + 1);
  } else if (value && typeof value === "object" && "name" in value && "version" in value) {
    ({ name, version } = value);
  }
  if (typeof name === "string" && name.trim() && typeof version === "string" && /^v[1-9]\d*$/.test(version))
    return { name, version };
}

/** Delimit an explicit reference in free text without interpreting the surrounding prose as an asset name. */
export function assetRefTag(ref: AssetRef): string {
  const body = formatAssetRef(ref).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
  return "<asset>" + body + "</asset>";
}

export function* assetRefTags(text: string): Generator<{ index: number; raw: string; ref?: AssetRef }> {
  // Legacy ref objects have string fields. Consume entire JSON strings so a closing tag inside a name stays part of it.
  const tags = /<asset>(\s*\{(?:[^"{}]|"(?:\\.|[^"\\])*")*\}\s*|.*?)<\/asset>/gs;
  for (const match of text.matchAll(tags)) {
    const body = match[1];
    let ref = parseAssetRef(body.replaceAll("&lt;", "<").replaceAll("&gt;", ">").replaceAll("&amp;", "&"));
    if (!ref && body.trimStart().startsWith("{")) {
      try { ref = parseAssetRef(JSON.parse(body)); } catch { /* Keep malformed text in its original position. */ }
    }
    yield { index: match.index, raw: match[0], ref };
  }
}

export function assetRefsInText(text: string): AssetRef[] {
  return Array.from(assetRefTags(text), ({ ref }) => {
    if (!ref) throw Error("Invalid asset reference: expected name@vN");
    return ref;
  });
}

/** Project existing tags into the current wire format while retaining the rest of a message verbatim. */
export function canonicalAssetTags(text: string): string {
  if (!text.includes("<asset>")) return text;
  let out = "", pos = 0;
  for (const { index, raw, ref } of assetRefTags(text)) {
    if (!ref) continue;
    out += text.slice(pos, index) + assetRefTag(ref);
    pos = index + raw.length;
  }
  return out + text.slice(pos);
}
/** Portable skill instructions generated by the main agent, not a backend-native skill name. */
export type WorkflowSkill = { name: string; description: string; content: string };
/** Immutable identity of a reused task agent. Assignment inputs stay on NodeDef. */
export type NodeAgentConfig = { systemPrompt?: string; skills?: WorkflowSkill[] };
export type NodeDef = {
  node: string;
  kind: "task" | "end";
  prompt?: string;
  input: Record<string, unknown>;
  model?: string;
  agent?: NodeAgentConfig;
  schema?: object;
  multi: boolean;
};
export type Edge = { from: string; to: string; case?: string };
export type WorkflowGraph = { nodes: NodeDef[]; edges: Edge[] };
/** A node as a view shows it: its definition's name and kind, where its work stands, and who did it. */
export type WorkflowNodeView = {
  name: string;
  kind: NodeDef["kind"];
  status: string;
  paused: boolean;
  /** The user's interruption of it got to its agent and is not handled yet (its turn failed or stopped): it holds the node until resumed. */
  interrupted?: boolean;
  agentId?: string;
  sessionId?: string;
  target?: string;
  summary?: string;
  additionalResults?: { id: string; summary: string }[];
  controls?: { pause: boolean; resume: boolean };
};

/**
 * A version that was active and was replaced: its graph and its nodes as they stood then. Kept to be looked at;
 * the conversations of its nodes can be read, not continued.
 */
export type WorkflowHistory = { version: string; retiredAt: string; nodes: WorkflowNodeView[]; edges: Edge[] };

export type WorkflowView = {
  /** Authoritative runtime state and actions; clients need not infer them from node labels. */
  state?: "empty" | "proposed" | "running" | "paused" | "completed";
  controls?: { pause: boolean; resume: boolean };
  /** Earlier active versions, the latest first. */
  history?: WorkflowHistory[];
  sessionId: string;
  version?: string;
  candidate?: { version: string; graph: WorkflowGraph };
  edges: Edge[];
  paused: boolean;
  /** An interruption from the main conversation holds the whole graph until it is handled, or the workflow resumed. */
  interrupted?: boolean;
  error?: string;
  nodes: WorkflowNodeView[];
};
